    /**
     * Build $count distinct items, deterministic for a given random source.
     *
     * @return array<int, array<string, mixed>>
     */
    public static function items(int $count, DemoRandom $random): array
    {
        $all = [];

        foreach (self::families() as $family) {
            [$category, $base, $unit, $brands, $sizes, $flavours, $seasons, $popularity] = $family;
            $flavours = $flavours === [] ? [''] : $flavours;

            foreach ($brands as [$brand, $origin, $factor]) {
                foreach ($flavours as $flavour) {
                    foreach ($sizes as [$sizeLabel, $price, $carton]) {
                        $name = trim(implode(' ', array_filter([$base, $flavour, $brand, $sizeLabel])));
                        $all[] = [
                            'name' => $name,
                            'category' => $category,
                            'brand' => $brand,
                            'origin' => $origin,
                            'unit' => $unit,
                            'carton' => (int) $carton,
                            'base_price' => $price * $factor,
                            'seasons' => $seasons,
                            // Family-level demand spread over its members, so a family
                            // with forty variants does not swamp the basket.
                            'family_weight' => $popularity,
                            'family' => $base,
                        ];
                    }
                }
            }
        }

        $familySizes = array_count_values(array_column($all, 'family'));
        $all = $random->shuffle($all);

        // Prefer breadth: take items round-robin across families so a reduced
        // scale still has rice, oil, tea and soap rather than forty biscuits.
        $byFamily = [];
        foreach ($all as $item) {
            $byFamily[$item['family']][] = $item;
        }

        $chosen = [];
        while (count($chosen) < $count && $byFamily !== []) {
            foreach (array_keys($byFamily) as $family) {
                $chosen[] = array_shift($byFamily[$family]);

                if ($byFamily[$family] === []) {
                    unset($byFamily[$family]);
                }

                if (count($chosen) >= $count) {
                    break;
                }
            }
        }

        $barcodes = [];

        foreach ($chosen as $index => &$item) {
            $jitter = $random->between(0.94, 1.06);
            $purchase = self::roundPrice($item['base_price'] * $jitter);
            $margin = self::MARGINS[$item['category']] * $random->between(0.8, 1.25);
            $item['purchase_price'] = $purchase;
            $item['sale_price'] = max(self::roundPrice($purchase * (1 + $margin)), $purchase + 1);
            $item['code'] = (string) (10001 + $index);
            $item['barcode'] = self::barcode($item['origin'], $random, $barcodes);
            $item['popularity'] = $item['family_weight'] / sqrt($familySizes[$item['family']]) * $random->between(0.3, 1.7);
            unset($item['base_price'], $item['family_weight']);
        }
        unset($item);

        return $chosen;
    }

    public static function roundPrice(float $price): float
    {
        if ($price >= 1000) {
            return round($price / 10) * 10;
        }

        if ($price >= 100) {
            return round($price / 5) * 5;
        }

        return max(round($price), 1);
    }

    /** A valid EAN-13 (or in-store 2xx code for local produce). */
    private static function barcode(string $origin, DemoRandom $random, array &$used): string
    {
        $prefix = self::GS1[$origin] ?? '200';

        do {
            $body = $prefix;
            while (strlen($body) < 12) {
                $body .= (string) $random->int(0, 9);
            }

            $sum = 0;
            for ($i = 0; $i < 12; $i++) {
                $sum += (int) $body[$i] * ($i % 2 === 0 ? 1 : 3);
            }

            $code = $body . ((10 - $sum % 10) % 10);
        } while (isset($used[$code]));

        $used[$code] = true;

        return $code;
    }
